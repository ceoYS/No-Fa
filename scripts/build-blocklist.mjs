#!/usr/bin/env node
/*
 * build-blocklist.mjs — compile a bundled domain list (the data contract) into the
 * declarativeNetRequest STATIC ruleset that Chrome actually loads, plus a small meta module the
 * service worker imports for honest status reporting.
 *
 * Default (no args) — compile the committed FIXTURE, in place:
 *   Source : extensions/chrome-shield/data/adult-domains.v1.json  (fixture, reserved-TLD domains)
 *   Emits  : extensions/chrome-shield/blocklist-rules.json         (Chrome static ruleset)
 *            extensions/chrome-shield/blocklist-meta.js            (version/listType/counts)
 *
 * Production promotion (RC-17 P0) — explicit, license-gated, writes GITIGNORED outputs only:
 *   node scripts/build-blocklist.mjs --promote-production
 *   Source : extensions/chrome-shield/data/adult-domains.production.json  (from fetch script)
 *   Emits  : extensions/chrome-shield/blocklist-rules.production.json     (gitignored)
 *            extensions/chrome-shield/blocklist-meta.production.js         (gitignored)
 * The committed fixture files are NEVER overwritten by promotion, so the repo keeps no real adult
 * domains (protected rule #5). Release packaging swaps the .production.* files into the extension zip.
 * Promotion refuses to run until the license review in data/BLOCKLIST_ATTRIBUTION.md is cleared.
 *
 * Matching uses `condition.requestDomains`, which matches each listed domain AND its subdomains
 * exactly (native, safe) — never substring. Bundled rules sit at priority 1; user allowlist (allow,
 * priority 3) and user blocks (priority 2) override them. No network, no external code.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { normalizeDomainToken, sha256Hex, canonicalDomainsJson } from './lib/blocklist-normalize.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const EXT = join(HERE, '..', 'extensions', 'chrome-shield');
const DATA = join(EXT, 'data');

// Bundled block rules sit below user rules. Allowlist (allow) = 3, user block = 2, bundled = 1.
const BUNDLED_PRIORITY = 1;
// ponytail: one rule per 1000 domains — well under Chrome's per-rule domain cap; raise/lower only
// if a production list ever trips a ruleset limit. Chunking keeps a large list valid without code.
const DOMAINS_PER_RULE = 1000;

function chunk(arr, n) {
  const out = [];
  for (let i = 0; i < arr.length; i += n) out.push(arr.slice(i, i + n));
  return out;
}

// Compile a domain array → { rules, meta }. Pure; shared by fixture + production paths so both emit
// byte-identical structure (only the domains + listType differ).
function compile(src) {
  if (src.schema !== 'nof.blocklist/v1') throw new Error(`unexpected schema: ${src.schema}`);
  const domains = [...new Set((src.domains || []).map(normalizeDomainToken).filter(Boolean))].sort();
  const rules = chunk(domains, DOMAINS_PER_RULE).map((requestDomains, i) => ({
    id: i + 1,
    priority: BUNDLED_PRIORITY,
    action: { type: 'redirect', redirect: { extensionPath: '/blocked.html' } },
    condition: { requestDomains, resourceTypes: ['main_frame'] },
  }));
  const meta = {
    version: src.version,
    listType: src.listType, // 'fixture' | 'production' — the service worker reports this honestly
    domainCount: domains.length,
    ruleCount: rules.length,
    updatedAt: src.updatedAt || new Date().toISOString().slice(0, 10),
    // compiledSha256 lets QA pin the exact compiled result deterministically (founder P0 #8).
    compiledSha256: sha256Hex(canonicalDomainsJson(domains)),
  };
  return { domains, rules, meta };
}

function metaModule(meta) {
  return (
    '// GENERATED by scripts/build-blocklist.mjs — do not edit by hand.\n' +
    '// The service worker imports this so GET_STATUS reports the REAL bundled list version/type/count.\n' +
    `export const BLOCKLIST_META = ${JSON.stringify(meta, null, 2)};\n`
  );
}

function buildFixture() {
  const src = JSON.parse(readFileSync(join(DATA, 'adult-domains.v1.json'), 'utf8'));
  if (src.listType !== 'fixture') throw new Error(`refusing: adult-domains.v1.json is not listType=fixture (${src.listType})`);
  const { domains, rules, meta } = compile(src);
  writeFileSync(join(EXT, 'blocklist-rules.json'), JSON.stringify(rules, null, 2) + '\n');
  writeFileSync(join(EXT, 'blocklist-meta.js'), metaModule(meta));
  console.log(`[build-blocklist] FIXTURE: ${domains.length} domains → ${rules.length} rule(s) · listType=${meta.listType} v${meta.version}`);
}

function promoteProduction() {
  const artifactPath = join(DATA, 'adult-domains.production.json');
  if (!existsSync(artifactPath)) {
    throw new Error('adult-domains.production.json not found. Run `node scripts/fetch-production-blocklist.mjs` first.');
  }
  // License gate — promotion is blocked until the attribution review is explicitly cleared.
  // Read the FLAG LINE only (line-anchored), never a mention of the flag in the doc's prose — the
  // attribution text itself contains the string "…CLEARED = YES" as an instruction, and a loose
  // substring match there would fail OPEN. The value must be exactly YES on its own flag line.
  const attribution = readFileSync(join(DATA, 'BLOCKLIST_ATTRIBUTION.md'), 'utf8');
  const flag = attribution.match(/^\s*PRODUCTION_BLOCKLIST_LICENSE_REVIEW_CLEARED\s*=\s*(\w+)/m);
  const cleared = !!flag && flag[1].toUpperCase() === 'YES';
  if (!cleared) {
    throw new Error(
      'PRODUCTION_BLOCKLIST_LICENSE_REVIEW_REQUIRED: promotion blocked. Clear the license review in\n' +
      '  extensions/chrome-shield/data/BLOCKLIST_ATTRIBUTION.md (set PRODUCTION_BLOCKLIST_LICENSE_REVIEW_CLEARED = YES)\n' +
      'only after a human has verified redistribution rights for every upstream source.',
    );
  }
  const src = JSON.parse(readFileSync(artifactPath, 'utf8'));
  if (src.listType !== 'production') throw new Error(`refusing: adult-domains.production.json is not listType=production (${src.listType})`);
  const { domains, rules, meta } = compile(src);
  // GITIGNORED outputs only — never the committed fixture files.
  writeFileSync(join(EXT, 'blocklist-rules.production.json'), JSON.stringify(rules, null, 2) + '\n');
  writeFileSync(join(EXT, 'blocklist-meta.production.js'), metaModule(meta));
  console.log(`[build-blocklist] PRODUCTION: ${domains.length} domains → ${rules.length} rule(s) · compiledSha256=${meta.compiledSha256}`);
  console.log('[build-blocklist] wrote GITIGNORED blocklist-rules.production.json + blocklist-meta.production.js');
  console.log('[build-blocklist] Release packaging swaps these into the extension zip. Do NOT commit them.');
}

function main() {
  if (process.argv.includes('--promote-production')) promoteProduction();
  else buildFixture();
}

main();
